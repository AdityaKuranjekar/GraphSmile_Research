"""Index every run in results/logs as evidence: configuration, completion, and final metrics.

Each row points at the raw log file, so a reviewer can open the log and check the numbers.
Usage (from the repository root):  python scripts/build_proof_index.py results/proof_index.md
"""
import datetime
import glob
import os
import re
import sys

LOG_DIR = 'results/logs'
NAMESPACE_RE = re.compile(r"Namespace\((.*)\)")
ARG_RE = re.compile(r"(\w+)=('[^']*'|\[[^\]]*\]|[^,\s]+)")
EPOCH_RE = re.compile(r'test_f1_emo: ([\d.]+)')
FINAL_RE = re.compile(r'^Acc: ([\d.]+), F-Score: ([\d.]+)', re.M)
KEYS = ['dataset', 'modals', 'loss_type', 'epochs', 'lr', 'l2', 'hidden_dim', 'batch_size']


def parse(path):
    text = open(path, encoding='utf-8', errors='replace').read()
    args = {}
    m = NAMESPACE_RE.search(text)
    if m:
        for key, value in ARG_RE.findall(m.group(1)):
            args[key] = value.strip("'")
    f1s = [float(x) for x in EPOCH_RE.findall(text)]
    best_epoch = (f1s.index(max(f1s)) + 1) if f1s else None
    final = FINAL_RE.search(text)
    return {
        'args': args,
        'epochs_run': len(f1s),
        'best_epoch': best_epoch,
        'completed': 'Test performance..' in text,
        'acc': final.group(1) if final else None,
        'f1': final.group(2) if final else None,
        'modified': datetime.datetime.fromtimestamp(os.path.getmtime(path))
                       .strftime('%Y-%m-%d %H:%M'),
    }


def main(out_path):
    rows = []
    for path in sorted(glob.glob(os.path.join(LOG_DIR, '*.log'))):
        name = os.path.basename(path)[:-4]
        ds, _, tag = name.partition('_')
        info = parse(path)
        a = info['args']
        cfg = ', '.join(f'{k}={a[k]}' for k in KEYS if k in a)
        status = 'completed' if info['completed'] else 'NOT completed'
        rows.append((ds, tag, status, info, cfg, path))

    with open(out_path, 'w', encoding='utf-8') as f:
        f.write('# Proof index: every run in results/logs\n\n')
        f.write('Generated by `scripts/build_proof_index.py` from the raw logs. '
                'Acc and F-Score are the values printed at the end of each run '
                '(`Test performance..` block), which are the maximum over epochs, as in `run.py`.\n\n')
        f.write('| Dataset | Variant | Status | Epochs run | Best-F1 epoch | Acc | F-Score | Log file | Config |\n')
        f.write('|---|---|---|---|---|---|---|---|---|\n')
        for ds, tag, status, info, cfg, path in rows:
            f.write(f"| {ds} | {tag} | {status} | {info['epochs_run']} | "
                    f"{info['best_epoch'] or 'n/a'} | {info['acc'] or 'n/a'} | "
                    f"{info['f1'] or 'n/a'} | `{path}` | {cfg} |\n")
    print(f'Wrote {out_path} ({len(rows)} runs)')


if __name__ == '__main__':
    main(sys.argv[1] if len(sys.argv) > 1 else 'results/proof_index.md')
